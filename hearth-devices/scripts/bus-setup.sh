#!/usr/bin/env bash
# Generates the bus identities for Mosquitto (safe to rerun; existing passwords are kept):
#   secrets/bus.env            BUS_PASSWORD_<USER>=… for every identity (0600, gitignored)
#   secrets/mosquitto/passwd   hashed with the image's mosquitto_passwd
#   secrets/mosquitto/acl      mirrors local-stack/src/bus.ts (local contract v1)
# Usage: scripts/bus-setup.sh [adapter-id ...]     (default adapters: fake)
set -euo pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
SECRETS="$DIR/secrets"; MQ="$SECRETS/mosquitto"; ENV="$SECRETS/bus.env"
IMAGE=$(awk '/image:/ {print $2; exit}' "$DIR/deploy/compose.yaml")
ADAPTERS=("${@:-fake}")
umask 077; mkdir -p "$MQ"; chmod 700 "$SECRETS" "$MQ"; touch "$ENV"

users=(core hub healthcheck)
for a in "${ADAPTERS[@]}"; do [[ "$a" =~ ^[a-z0-9][a-z0-9-]*$ ]] || { echo "bad adapter id: $a" >&2; exit 2; }; users+=("adapter-$a"); done

key() { echo "BUS_PASSWORD_$(echo "$1" | tr 'a-z-' 'A-Z_')"; }
for u in "${users[@]}"; do
  k=$(key "$u")
  grep -q "^$k=" "$ENV" || { [ "$u" = healthcheck ] && p=healthcheck || p=$(openssl rand -hex 24); echo "$k=$p" >> "$ENV"; }
done

# Plain "user:password" lines, hashed in place by mosquitto_passwd -U inside the pinned image.
: > "$MQ/passwd"
for u in "${users[@]}"; do echo "$u:$(grep "^$(key "$u")=" "$ENV" | cut -d= -f2-)" >> "$MQ/passwd"; done
docker run --rm --user "$(id -u):$(id -g)" -v "$MQ:/s" "$IMAGE" mosquitto_passwd -U /s/passwd

{
  echo "# Generated by scripts/bus-setup.sh. Mirrors local-stack/src/bus.ts (local contract v1)."
  echo "user core"
  echo "topic read hearth/local/#"
  echo "topic write hearth/local/devices/+/set"
  echo "topic write hearth/local/core/registry"
  echo "topic write hearth/local/core/response/+"
  echo
  echo "user hub"
  echo "topic write hearth/local/core/request/hub"
  echo "topic read hearth/local/core/response/hub"
  echo "topic read hearth/local/core/registry"
  echo
  echo "user healthcheck"
  echo "topic read \$SYS/broker/uptime"
  for a in "${ADAPTERS[@]}"; do
    echo
    echo "user adapter-$a"
    echo "topic write hearth/local/devices/+/meta"
    echo "topic write hearth/local/devices/+/state"
    echo "topic write hearth/local/devices/+/result"
    echo "topic write hearth/local/adapters/$a/status"
    echo "topic read hearth/local/devices/+/set"
  done
} > "$MQ/acl"
chmod 600 "$MQ"/* "$ENV"
echo "identities: ${users[*]}"
echo "wrote $ENV, $MQ/passwd (hashed), $MQ/acl"
